#!/usr/bin/env python3
"""Generate src/pp/asic_reg/: amdgpu's register headers, trimmed to what the
vendored powerplay code (src/pp/upstream) can name.

The upstream headers (drivers/gpu/drm/amd/include/asic_reg/) are several MB.
This keeps each header at its include path, with only the #defines that some
vendored source token can reach:
  - NAME itself appears as a token;
  - mmNAME / ixNAME / cfgNAME whose bare NAME appears (the code pastes mm##reg);
  - REG__FIELD_MASK / REG__FIELD__SHIFT whose REG appears (reg##__##field).
Values are copied unchanged, so the vendored objects compile byte for byte the
same as against the full headers (check with `make pp-regs-check`).

usage: gen_pp_regs.py <asic_reg dir> <linux commit sha> <vendored src dir> <out dir>
"""
import os
import re
import sys

HEADERS = [
    "smu/smu_7_1_3", "smu/smu_7_1_2", "gmc/gmc_8_1", "bif/bif_5_0", "oss/oss_3_0",
    "gca/gfx_8_0", "dce/dce_10_0", "dce/dce_11_0",
]
DEFINE = re.compile(r"^#define\s+(\S+)\s+(\S+)")
TOKEN = re.compile(r"[A-Za-z_][A-Za-z0-9_]*")
PREFIXES = ("mm", "ix", "cfg")


def tokens(src):
    out = set()
    for root, _, files in os.walk(src):
        for f in files:
            if f.endswith((".c", ".h")):
                with open(os.path.join(root, f), errors="replace") as fh:
                    out.update(TOKEN.findall(fh.read()))
    return out


def wanted(name, toks):
    if name in toks:
        return True
    for p in PREFIXES:
        if name.startswith(p) and name[len(p):] in toks:
            return True
    if "__" in name and name.split("__", 1)[0] in toks:
        return True
    return False


def main():
    if len(sys.argv) != 5:
        sys.exit(__doc__)
    regs, sha, src, out = sys.argv[1:]
    toks = tokens(src)
    for h in HEADERS:
        for suffix in ("_d.h", "_sh_mask.h"):
            path = os.path.join(regs, h + suffix)
            kept, total = [], 0
            with open(path) as fh:
                for line in fh:
                    m = DEFINE.match(line)
                    if not m:
                        continue
                    total += 1
                    if wanted(m.group(1), toks):
                        kept.append(line.rstrip() + "\n")
            guard = "RG_PP_" + re.sub(r"\W", "_", h + suffix).upper()
            dst = os.path.join(out, h + suffix)
            os.makedirs(os.path.dirname(dst), exist_ok=True)
            with open(dst, "w") as fh:
                fh.write(f"/* Generated by tools/gen_pp_regs.py from Linux amdgpu (MIT) at {sha},\n")
                fh.write(f" * drivers/gpu/drm/amd/include/asic_reg/{h}{suffix}: {len(kept)} of {total} defines,\n")
                fh.write(" * the ones src/pp/upstream can name. Do not edit; regenerate. */\n")
                fh.write(f"#ifndef {guard}\n#define {guard}\n\n")
                fh.writelines(kept)
                fh.write(f"\n#endif\n")
            print(f"{h}{suffix}: {len(kept)}/{total}", file=sys.stderr)


if __name__ == "__main__":
    main()
