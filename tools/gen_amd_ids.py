#!/usr/bin/env python3
"""Generate src/amd_ids.inc from the Linux amdgpu driver's PCI ID table.

usage: tools/gen_amd_ids.py path/to/amdgpu_drv.c <linux-commit-sha> > src/amd_ids.inc

Only the explicit per-device entries are taken. Devices newer than that table
(RDNA3, RDNA4, CDNA3 and later) are matched by class in amdgpu and identified
at runtime from the GPU's IP-discovery table, so they are absent here by design.
"""
import re
import sys

ENTRY = re.compile(r"PCI_DEVICE\(0x1002,\s*0x([0-9A-Fa-f]{4})\),\s*\.driver_data\s*=\s*([A-Z0-9_|]+)")


def main() -> int:
    if len(sys.argv) != 3:
        print(__doc__, file=sys.stderr)
        return 2
    path, sha = sys.argv[1], sys.argv[2]
    rows = []
    with open(path, encoding="utf-8") as f:
        for m in ENTRY.finditer(f.read()):
            dev = int(m.group(1), 16)
            parts = m.group(2).split("|")
            chip = next(p for p in parts if p.startswith("CHIP_"))
            if chip == "CHIP_IP_DISCOVERY":
                continue
            flags = []
            if "AMD_IS_APU" in parts:
                flags.append("RG_AMD_APU")
            if "AMD_IS_MOBILITY" in parts:
                flags.append("RG_AMD_MOBILITY")
            if "AMD_EXP_HW_SUPPORT" in parts:
                flags.append("RG_AMD_EXPERIMENTAL")
            rows.append((dev, chip[len("CHIP_"):], "|".join(flags) or "0"))

    print("/* Generated by tools/gen_amd_ids.py -- do not edit by hand.")
    print(f" * Source: linux drivers/gpu/drm/amd/amdgpu/amdgpu_drv.c @ {sha}")
    print(" * (amdgpu is MIT-licensed; see the header of that file.) */")
    print("static const rg_amd_id rg_amd_ids[] = {")
    for dev, chip, flags in rows:
        print(f'  {{0x{dev:04X}, "{chip}", {flags}}},')
    print("};")
    print(f"/* {len(rows)} entries */")
    return 0


if __name__ == "__main__":
    sys.exit(main())
