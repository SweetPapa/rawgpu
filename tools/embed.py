#!/usr/bin/env python3
"""Embed binary files in C: tools/embed.py OUT.c NAME=FILE... defines
const unsigned char rawgpu_embedded_NAME[] and size_t rawgpu_embedded_NAME_size."""
import sys

out = [f"/* generated by tools/embed.py from {' '.join(a.split('=', 1)[1] for a in sys.argv[2:])}; do not edit */",
       "#include <stddef.h>"]
for arg in sys.argv[2:]:
    name, path = arg.split("=", 1)
    data = open(path, "rb").read()
    out.append(f"const unsigned char rawgpu_embedded_{name}[] __attribute__((aligned(16))) = {{")
    for i in range(0, len(data), 24):
        out.append("  " + ",".join(str(b) for b in data[i:i + 24]) + ",")
    out.append("};")
    out.append(f"const size_t rawgpu_embedded_{name}_size = {len(data)};")
open(sys.argv[1], "w").write("\n".join(out) + "\n")
