#!/usr/bin/env python3
"""Generate src/atom/rg_atom_names.inc: ATOM command/data table names by index.

usage: tools/gen_atom_names.py src/atom/upstream/atombios.h > src/atom/rg_atom_names.inc

The names are the field names of ATOM_MASTER_LIST_OF_COMMAND_TABLES and
ATOM_MASTER_LIST_OF_DATA_TABLES; a table's index is its field position.
"""
import re
import sys

FIELD = re.compile(r"^\s*USHORT\s+(\w+)\s*;")


def fields(text: str, struct: str) -> list[str]:
    start = text.index(f"typedef struct _{struct}")
    end = text.index(f"}}{struct};", start)
    return [m.group(1) for line in text[start:end].splitlines() if (m := FIELD.match(line))]


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__, file=sys.stderr)
        return 2
    text = open(sys.argv[1], encoding="latin-1").read()
    print("/* Generated by tools/gen_atom_names.py from src/atom/upstream/atombios.h -- do not edit. */")
    for kind, struct in (("cmd", "ATOM_MASTER_LIST_OF_COMMAND_TABLES"), ("data", "ATOM_MASTER_LIST_OF_DATA_TABLES")):
        names = fields(text, struct)
        print(f"static const char *const rg_atom_{kind}_names[{len(names)}] = {{")
        for n in names:
            print(f'  "{n}",')
        print("};")
    return 0


if __name__ == "__main__":
    sys.exit(main())
